def get_lesson_content(topic: str, lesson_slug: str) -> dict:
    """
    Retrieve the full content of a specific lesson.

    Args:
        topic: Topic area — one of: docker, kubernetes, helm, observability, gitops
        lesson_slug: Lesson filename without extension, e.g. '06-enterprise-networking'

    Returns:
        dict with 'content' (markdown text) and 'path' fields.
    """
    lesson_path = CONTENT_DIR / topic / f"{lesson_slug}.md"
    if not lesson_path.exists():
        # Try finding by partial match
        matches = list((CONTENT_DIR / topic).glob(f"*{lesson_slug}*")) if (CONTENT_DIR / topic).exists() else []
        if not matches:
            return {"error": f"Lesson not found: {topic}/{lesson_slug}", "available": list_lessons(topic)}
        lesson_path = matches[0]

    return {
        "path": str(lesson_path.relative_to(CONTENT_DIR)),
        "content": lesson_path.read_text(),
    }


def list_lessons(topic: str = None) -> dict:
    """
    List available lessons, optionally filtered by topic.

    Args:
        topic: Optional topic filter (docker, kubernetes, helm, observability, gitops)

    Returns:
        dict mapping topics to lists of lesson filenames.
    """
    result = {}
    if topic:
        topics = [topic]
    else:
        topics = [d.name for d in CONTENT_DIR.iterdir() if d.is_dir()]

    for t in topics:
        topic_dir = CONTENT_DIR / t
        if topic_dir.exists():
            result[t] = sorted([f.stem for f in topic_dir.glob("*.md")])

    return result


def get_lab_exercise(topic: str, lab_name: str) -> dict:
    """
    Retrieve a hands-on lab exercise with its instructions and YAML files.

    Args:
        topic: Topic area (docker, kubernetes, helm)
        lab_name: Lab directory name, e.g. '01-network-policies'

    Returns:
        dict with lab README content and any accompanying YAML/Dockerfile content.
    """
    lab_path = LABS_DIR / topic / lab_name
    if not lab_path.exists():
        available = [d.name for d in (LABS_DIR / topic).iterdir() if d.is_dir()] if (LABS_DIR / topic).exists() else []
        return {"error": f"Lab not found: {topic}/{lab_name}", "available": available}

    files = {}
    for f in sorted(lab_path.glob("**/*")):
        if f.is_file():
            rel = str(f.relative_to(lab_path))
            files[rel] = f.read_text()

    return {"lab": lab_name, "topic": topic, "files": files}


