# ─── API models ───────────────────────────────────────────────────────────────

class ChatRequest(BaseModel):
    message: str
    session_id: str
    user_id: str = "anonymous"

class ChatResponse(BaseModel):
    response: str
    session_id: str
    tool_calls: list[dict] = []

# ─── Endpoints ────────────────────────────────────────────────────────────────

@app.post("/chat", response_model=ChatResponse)
async def chat(request: ChatRequest):
    """Send a message to the DevOps AI tutor and get a response."""
    from google.genai import types

    # Ensure session exists
    try:
        await session_service.get_session(
            app_name=APP_NAME,
            user_id=request.user_id,
            session_id=request.session_id,
        )
    except Exception:
        await session_service.create_session(
            app_name=APP_NAME,
            user_id=request.user_id,
            session_id=request.session_id,
        )

    user_message = types.Content(
        role="user",
        parts=[types.Part(text=request.message)],
    )

    final_response = ""
    tool_calls_made = []

    async for event in runner.run_async(
        user_id=request.user_id,
        session_id=request.session_id,
        new_message=user_message,
    ):
        if event.is_final_response() and event.content:
            final_response = "".join(
                p.text for p in event.content.parts if hasattr(p, "text")
            )
        # Capture tool calls for transparency
        if hasattr(event, "tool_call") and event.tool_call:
            tool_calls_made.append({
                "tool": event.tool_call.name,
                "args": dict(event.tool_call.args),
            })

    return ChatResponse(
        response=final_response,
        session_id=request.session_id,
        tool_calls=tool_calls_made,
    )


@app.get("/chat/stream")
async def chat_stream(message: str, session_id: str, user_id: str = "anonymous"):
    """Stream the AI tutor response token by token (SSE)."""
    from google.genai import types

    async def generate():
        try:
            await session_service.get_session(
                app_name=APP_NAME, user_id=user_id, session_id=session_id
            )
        except Exception:
            await session_service.create_session(
                app_name=APP_NAME, user_id=user_id, session_id=session_id
            )

        user_message = types.Content(
            role="user", parts=[types.Part(text=message)]
        )

        async for event in runner.run_async(
            user_id=user_id, session_id=session_id, new_message=user_message
        ):
            if event.content and event.content.parts:
                for part in event.content.parts:
                    if hasattr(part, "text") and part.text:
                        yield f"data: {part.text}\n\n"

        yield "data: [DONE]\n\n"

    return StreamingResponse(generate(), media_type="text/event-stream")


